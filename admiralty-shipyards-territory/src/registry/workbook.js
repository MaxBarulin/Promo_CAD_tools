// Книга Excel реестра: лист «Реестр» (все поля, статус ЭПБ с заливкой) и лист «Справка».

import { writeXlsx } from './xlsx.js';
import { COLUMNS, FIELDS, toRows, parseDate, columnGroups } from './core.js';

// заливки: срок ЭПБ по статусу (красная/жёлтая/зелёная), признаки ОПО «да» — зелёная, консервация «да» — синяя
const STATUS_STYLE = { 'Срок истёк': 4, Истекает: 5, 'В порядке': 6 };
const cellStyleOf = (c) => {
  if (c.key === 'epbStatus') return (v) => STATUS_STYLE[v] || 0;
  if (c.key === 'epbUntil') return (v, row) => STATUS_STYLE[row.epbStatus] || 0;
  if (c.key === 'conserved') return (v) => (v === 'да' ? 10 : 0);
  if (c.flag) return (v) => (v === 'да' ? 6 : 0);
  return undefined;
};

export function registryXlsx(items, records, { years = 2, demo = false, filterNote = '' } = {}) {
  const rows = toRows(items, records, years);
  const columns = COLUMNS.map((c) => ({
    ...c,
    parseDate: c.date ? parseDate : undefined,
    cellStyle: cellStyleOf(c),
    wrap: c.key === 'note',
    input: !!c.field,
  }));
  const today = new Date();
  const info = [
    ['Выгрузка', `${String(today.getDate()).padStart(2, '0')}.${String(today.getMonth() + 1).padStart(2, '0')}.${today.getFullYear()}`],
    ['Объектов в выгрузке', String(rows.length)],
    ...(filterNote ? [['Отбор', filterNote]] : []),
    ...(demo ? [['ВНИМАНИЕ', 'Демо-режим: поля ОПО, ЭПБ и технического состояния заполнены условными значениями для показа возможностей. Это условные значения.']] : []),
    ['Статус ЭПБ', `По сроку безопасной эксплуатации: «Срок истёк» — дата уже прошла; «Истекает» — в ближайшие ${years} г.; «В порядке» — позже; «Нет данных» — срок не указан.`],
    ['Как заполнить', `Впишите данные в столбцы с жёлтой шапкой: ${FIELDS.map((f) => f.label).join(', ')}. Столбец «Код в модели» (последний) не меняйте — по нему строки сопоставляются с объектами. Даты — в формате ДД.ММ.ГГГГ. Столбец «Инвентарный №» уже заполнен, при необходимости поправьте. Затем загрузите файл в реестр кнопкой «Загрузить таблицу».`],
    ['Группы столбцов', 'Здание — сведения об объекте. Промэкспертиза — заключение ЭПБ: его номер, регистрационный номер в Ростехнадзоре, дата и срок безопасной эксплуатации (ячейка срока залита по статусу). ОПО — класс опасности, рег. № ОПО и признаки, по которым здание входит в состав ОПО: сети газопотребления (газ), подъёмные сооружения (краны). Состояние — техническое состояние, дата обследования, консервация, примечание. Размеры по модели и Размещение — расчётные показатели и подразделения. Модель — служебные сведения, код в модели.'],
    ['Выпадающие списки', 'В столбцах «Класс ОПО», «Техническое состояние», «ОПО: газ», «ОПО: краны» и «Консервация» значение выбирается из списка: выделите ячейку и нажмите стрелку справа от неё. Если Excel открыл файл в режиме защищённого просмотра, сначала нажмите «Разрешить редактирование». Значения не из списка, неверные даты и год постройки вне 1700–2100 при загрузке в реестр пропускаются; для «да/нет» принимаются и «+»/«−».'],
    ['Размеры по модели', 'Длина и ширина — стороны наименьшего прямоугольника, описанного вокруг контура (для сложных контуров — габариты по внешним граням). Площадь застройки — по контуру здания (за вычетом дворов). Этажность — по OpenStreetMap, для цехов и складов без данных — 1, для остальных — по высоте. Общая площадь — площадь застройки × этажность. Строительный объём — площадь застройки × высоту до средней отметки кровли. Высоты цехов верфи в открытых данных отсутствуют и оценены по назначению и размерам, объём по ним — тоже оценка.'],
  ];
  return writeXlsx([
    { name: 'Реестр', columns, rows, groups: columnGroups(COLUMNS) },
    {
      name: 'Справка',
      columns: [
        { key: 'k', label: 'Параметр', w: 26 },
        { key: 'v', label: 'Значение', w: 110, wrap: true },
      ],
      rows: info.map(([k, v]) => ({ k, v })),
      freeze: false,
      filter: false,
    },
  ]);
}
