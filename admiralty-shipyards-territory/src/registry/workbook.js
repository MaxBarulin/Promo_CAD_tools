// Книга Excel реестра: лист «Реестр» (все поля, статус ЭПБ с заливкой) и лист «Справка».

import { writeXlsx } from './xlsx.js';
import { COLUMNS, FIELDS, toRows, parseDate } from './core.js';

const STATUS_STYLE = { 'Срок истёк': 4, Истекает: 5, 'В порядке': 6 };

export function registryXlsx(items, records, { years = 2, demo = false, filterNote = '' } = {}) {
  const rows = toRows(items, records, years);
  const columns = COLUMNS.map((c) => ({
    ...c,
    parseDate: c.date ? parseDate : undefined,
    statusStyle: c.key === 'epbStatus' ? (v) => STATUS_STYLE[v] || 0 : undefined,
    wrap: c.key === 'note',
    input: !!c.field,
  }));
  const today = new Date();
  const info = [
    ['Выгрузка', `${String(today.getDate()).padStart(2, '0')}.${String(today.getMonth() + 1).padStart(2, '0')}.${today.getFullYear()}`],
    ['Объектов в выгрузке', String(rows.length)],
    ...(filterNote ? [['Отбор', filterNote]] : []),
    ...(demo ? [['ВНИМАНИЕ', 'Демо-режим: поля ОПО, ЭПБ и технического состояния заполнены условными значениями для показа возможностей. Это условные значения.']] : []),
    ['Статус ЭПБ', `По сроку безопасной эксплуатации: «Срок истёк» — дата уже прошла; «Истекает» — в ближайшие ${years} г.; «В порядке» — позже; «Нет данных» — срок не указан.`],
    ['Как заполнить', `Впишите данные в столбцы с жёлтой шапкой: ${FIELDS.map((f) => f.label).join(', ')}. Столбец «Код в модели» не меняйте — по нему строки сопоставляются с объектами. Даты — в формате ДД.ММ.ГГГГ. Столбец «Инвентарный №» уже заполнен, при необходимости поправьте. Затем загрузите файл в реестр кнопкой «Загрузить таблицу».`],
    ['Выпадающие списки', 'В столбцах «Класс ОПО» и «Техническое состояние» значение выбирается из списка: выделите ячейку и нажмите стрелку справа от неё. Если Excel открыл файл в режиме защищённого просмотра, сначала нажмите «Разрешить редактирование». Значения не из списка, неверные даты и год постройки вне 1700–2100 при загрузке в реестр пропускаются.'],
    ['Расчётные показатели', 'Площадь застройки — по контуру здания (за вычетом дворов). Этажность — по OpenStreetMap, для цехов и складов без данных — 1, для остальных — по высоте. Общая площадь — площадь застройки × этажность. Строительный объём — площадь застройки × высоту до средней отметки кровли. Высоты цехов верфи в открытых данных отсутствуют и оценены — такие строки отмечены в столбце «Высота оценена».'],
  ];
  return writeXlsx([
    { name: 'Реестр', columns, rows },
    {
      name: 'Справка',
      columns: [
        { key: 'k', label: 'Параметр', w: 26 },
        { key: 'v', label: 'Значение', w: 110, wrap: true },
      ],
      rows: info.map(([k, v]) => ({ k, v })),
      freeze: false,
      filter: false,
    },
  ]);
}
